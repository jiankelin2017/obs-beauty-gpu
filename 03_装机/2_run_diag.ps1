# =====================================================================
param([string]$ShaderDir = "", [string]$Collection = "beauty_test", [int]$Seconds = 22, [string]$AbTarget = "", [switch]$Ab)

#  GPU tone / smooth diagnostic - run step  (normal user, no admin needed)
#  Launches OBS with BEAUTY_GPU=1 BEAUTY_GPU_TONE=1 BEAUTY_GPU_SMOOTH=1,
#  waits, then prints the self-check lines from the fresh log.
#
#  -ShaderDir <folder>  (optional) load *.hlsl straight from that folder via
#  BEAUTY_SHADER_DIR instead of the installed data dir, so shaders can be
#  iterated on without an admin install. Requires obs-beauty 3.1.42+.
#
#  -Collection <name>   (optional) scene collection to load, default beauty_test.
#  The 4K run uses phase0_baseline (generated by phase0_prep.py under the
#  verify folder, --mode scene --canvas 3840x2160), so the 720p camera
#  collection stays intact.
#
#  NOTE: pure ASCII on purpose (see 1_install_diag.ps1 header). All log
#  matching uses ASCII anchors, because the plugin log lines are Chinese:
#  "maxdiff=" and "smooth.hlsl" / "tone.hlsl" are the only ASCII tokens.
#
#  WARNING - this run can CHANGE the profile canvas. OBS applies the scene
#  collection's stored resolution when it loads one, so a run against a
#  1280x720 / 4K test collection can leave BaseCX/BaseCY switched after you
#  exit OBS. If you stream in a fixed canvas, check Settings > Video after a
#  diagnostic run (or restore basic.ini) before going live.
# =====================================================================
$ErrorActionPreference = "Stop"

$obsRoot = "C:\Program Files\obs-studio"
$exe     = Join-Path $obsRoot "bin\64bit\obs64.exe"
$bin     = Join-Path $obsRoot "bin\64bit"
$logDir  = Join-Path $env:APPDATA "obs-studio\logs"
# How long to wait before reading the log.  22 s is enough for the one-shot
# self-check lines, but NOT for the 3.1.57 A/B arms: one arm lasts 180 frames
# (3 s at 60 fps, 6 s at 30 fps), so a trustworthy A/B needs tens of windows.
# Pass -Seconds 240 -Ab for an A/B run; the script does not kill OBS, it just
# waits that long before reading, so a longer value costs nothing but patience.
# Without -Ab the run measures the shipped production behaviour (one arm), which
# is what 2_run_diag.bat / 4_run_4k.bat should report.
$wait    = $Seconds

# The previous diagnostic run's OBS is often still shutting down when the next
# launcher is double-clicked (720p -> 4K is usually a few seconds apart). A bare
# throw makes that second run flash and die with no log at all, which looks like
# "the 4K run produced nothing". So wait up to 60 s for it to exit first.
$waited = 0
while ((Get-Process obs64 -ErrorAction SilentlyContinue) -and $waited -lt 60000) {
    if ($waited -eq 0) {
        Write-Host "obs64 is still running (previous run?). Waiting up to 60 s ..."
    }
    Start-Sleep -Milliseconds 500
    $waited += 500
}
if (Get-Process obs64 -ErrorAction SilentlyContinue) {
    throw "obs64.exe already running. Close it first, then run this again."
}
if ($waited -gt 0) { Write-Host "obs64 exited after $waited ms - continuing." }
if (-not (Test-Path $exe)) { throw "MISSING $exe" }

# env vars are inherited by the child process
#
# Only BEAUTY_GPU is set here on purpose: as of 3.1.41 the BEAUTY_GPU=1 ->
# BEAUTY_ENGINE_IMPL=gpu mapping happens at the very top of obs_module_load(),
# i.e. before the engine singleton is created. So this run doubles as the
# regression test for that fix. BEAUTY_ENGINE_IMPL is deliberately NOT set,
# otherwise it would mask the bug again.
#
# BEAUTY_GPU_SMOOTH (3.1.45) runs the smoothing shader chain once and diffs it
# against the CPU surface3RgbBand output. Same "diagnostic only" contract as
# the tone pass: buf_out / out_tex are not touched.
$env:BEAUTY_GPU          = "1"
$env:BEAUTY_GPU_TONE     = "1"
$env:BEAUTY_GPU_SMOOTH   = "1"
# T1 (3.1.55): one-shot GPU detail diff against the CPU detailRefill baseline.
# Same "diagnostic only" contract: runs a standalone stateless detail pass
# (emaOn=0, base = original frame) and logs maxdiff / avg / change amount.
# buf_out / out_tex are not touched. Requires the chain hook to claim DETAIL
# on some frame (it stashes the engine-computed job.detail for this diff).
$env:BEAUTY_GPU_DETAIL   = "1"
# 5c (3.1.62): one-shot GPU warp diff against the CPU warpFaceWithGeom baseline.
# Same "diagnostic only" contract: runs the warp pass on the ORIGINAL frame with
# the exact geometry the chain hook used, then diffs it against a CPU run of the
# same geometry.  Expects maxdiff <= 1 (float last-bit rounding only).
# Requires the chain hook to claim WARP on some frame, which needs the three
# warp sliders (thin face / big eye / chin) to be non-zero in the filter.
$env:BEAUTY_GPU_WARP     = "1"
# 5b-2 (3.1.64): one-shot GPU mask diff (M1 gate). Builds the skin/eye masks with
# mask.hlsl from the engine's own geometry and compares them pixel by pixel with
# the CPU mask the production chain still uses. Diagnostic only -- the picture is
# untouched. Skipped on multi-face frames (slice 1 supports a single face).
$env:BEAUTY_GPU_MASK_CMP = "1"
# 3.1.47: turn on the 180-frame performance window so the new per-segment
# breakdown line (the one starting with "seg ") actually gets emitted.  Without
# it the engine still measures, but nothing is printed (prof_on == false).
$env:BEAUTY_PROFILE      = "1"
# 3.1.49 / Phase 3.5: GPU smoothing on the PRODUCTION path.  Unlike
# BEAUTY_GPU_SMOOTH above (diagnostic only, picture untouched), this one DOES
# change the picture - the CPU surface3RgbBand call is replaced by the shader
# chain.  Falls back to CPU per frame whenever the hook cannot run.
$env:BEAUTY_GPU_SMOOTH_PROD = "1"
# 3.1.57 / T2: same-session A/B of the Phase 5a chain hook.  BEAUTY_CHAIN_PROD
# is read only once at filter-create time, so it cannot flip an existing
# instance; this switch makes the plugin alternate arms every 180 frames
# (= exactly one log window) and tag each window with ab=chain or ab=1seg.
# Because the arm is constant inside a window, adjacent windows are a fair
# pair.  Requires BEAUTY_PROFILE=1.  Production behaviour is unchanged when
# this is not set.
# 3.1.60: opt-in via -Ab (5_run_ab.bat passes it).  It used to be always on,
# which meant every diagnostic run reported MIXED-arm numbers instead of what
# production actually does.  Plain 2_run_diag / 4_run_4k runs now measure the
# shipped behaviour.
if ($Ab -or $AbTarget -ne "") { $env:BEAUTY_CHAIN_AB = "1" }
else { Remove-Item Env:\BEAUTY_CHAIN_AB -ErrorAction SilentlyContinue }
# 3.1.58 / 5b-1: tail no-readback.  When every segment of the frame is claimed
# the chain hook skips the map+memcpy and hands its final texture to the host,
# which draws it directly (no alpha pass, no set_image upload).
# 3.1.60: this is now the DEFAULT, so it is deliberately NOT set here -- these
# runs must exercise the shipped default, not an env override.  Set it to "0"
# to fall back to the old read-back path.  See BEAUTY_CHAINOUT_CMP below.
# $env:BEAUTY_CHAIN_OUT  = "1"
# One-shot pixel check of the DRAW path: renders "direct texture + opaque blend"
# and "read-back + upload + SRC_ALPHA blend" into scratch render targets and
# diffs them.  Expects RGB maxdiff=0 and B's alpha == 255 everywhere; alpha
# differences are expected (direct draw passes the source alpha through) and
# are reported separately.  Costs one frame, safe to leave on.
$env:BEAUTY_CHAINOUT_CMP = "1"
# Which switch the A/B flips.  Empty = the chain hook (arms chain / 1seg, T2).
# "out" = the 5b-1 no-readback switch (arms out / rb).
if ($AbTarget -ne "") { $env:BEAUTY_AB_TARGET = $AbTarget }
else { Remove-Item Env:\BEAUTY_AB_TARGET -ErrorAction SilentlyContinue }
Remove-Item Env:\BEAUTY_ENGINE_IMPL -ErrorAction SilentlyContinue

# Load *.hlsl from -ShaderDir when given (BEAUTY_SHADER_DIR override).
if ($ShaderDir -ne "") {
    if (-not (Test-Path (Join-Path $ShaderDir "tone.hlsl"))) {
        throw "tone.hlsl not found in $ShaderDir"
    }
    if (-not (Test-Path (Join-Path $ShaderDir "smooth.hlsl"))) {
        throw "smooth.hlsl not found in $ShaderDir"
    }
    if (-not (Test-Path (Join-Path $ShaderDir "warp.hlsl"))) {
        throw "warp.hlsl not found in $ShaderDir"
    }
    $env:BEAUTY_SHADER_DIR = $ShaderDir
    Write-Output "shader source: $ShaderDir (override)"
} else {
    Remove-Item Env:\BEAUTY_SHADER_DIR -ErrorAction SilentlyContinue
    Write-Output "shader source: installed data dir"
}

$before = @(Get-ChildItem $logDir -Filter *.txt -ErrorAction SilentlyContinue |
            Select-Object -ExpandProperty Name)

Write-Output "launching OBS (BEAUTY_GPU=1 GPU_TONE=1 GPU_SMOOTH=1 collection=$Collection) ..."
Start-Process -FilePath $exe -ArgumentList "--collection", $Collection -WorkingDirectory $bin

Start-Sleep -Seconds $wait

$log = Get-ChildItem $logDir -Filter *.txt |
       Where-Object { $before -notcontains $_.Name } |
       Sort-Object LastWriteTime -Descending |
       Select-Object -First 1

if (-not $log) { throw "no new log file appeared in $logDir" }

Write-Output ""
Write-Output "================ LOG: $($log.Name) ================"
Write-Output ""
Write-Output "---- version ----"
Select-String -Path $log.FullName -Pattern 'filter registered|init OK' | ForEach-Object { $_.Line }
Write-Output ""
Write-Output "---- shader / load path ----"
Select-String -Path $log.FullName -Pattern 'tone\.hlsl|smooth\.hlsl|detail\.hlsl|warp\.hlsl' | ForEach-Object { $_.Line }
Write-Output ""
Write-Output "---- SELF CHECK (maxdiff) ----"
$hit = Select-String -Path $log.FullName -Pattern 'maxdiff='
if ($hit) { $hit | ForEach-Object { $_.Line } }
else { Write-Output "(NOT FOUND - filter not rendering, or shader failed to load)" }
Write-Output ""
Write-Output "---- per-segment timing (3.1.47) ----"
# ASCII anchor "seg " is emitted on purpose by the plugin; never match a Chinese
# label here, this file must stay pure ASCII.
$hit = Select-String -Path $log.FullName -Pattern '\] seg '
if ($hit) { $hit | ForEach-Object { $_.Line } }
else { Write-Output "(NOT FOUND - needs BEAUTY_PROFILE=1 and >=180 rendered frames)" }
Write-Output ""
Write-Output "---- GPU smoothing take-over (3.1.49) ----"
# "gpusm=" is appended to the seg line itself, so this also shows the segment
# breakdown.  hits/calls = frames the shader chain actually took over.
$hit = Select-String -Path $log.FullName -Pattern 'gpusm='
if ($hit) { $hit | ForEach-Object { $_.Line } }
else { Write-Output "(NOT FOUND - production path off, or panel smoothing = 0)" }
Write-Output ""
Write-Output "---- GPU smooth 3-way split (3.1.50) ----"
# "sm=" is appended to the same seg line: draw/map/copy inside the smoothing
# segment.  draw = command submission (deferred, D3D11),  map = GPU->CPU sync
# and download (this is where the real GPU cost lands),  copy = memcpy to dst.
$hit = Select-String -Path $log.FullName -Pattern ' sm='
if ($hit) { $hit | ForEach-Object { $_.Line } }
else { Write-Output "(NOT FOUND - needs 3.1.50+ and >=1 taken-over frame)" }
Write-Output ""
Write-Output "---- A/B arms (3.1.57) ----"
# Every perf line ends with ab=<arm>.  Grouping these two sets and comparing
# their medians is the whole point of T2: both arms ran in the SAME session, so
# background load cancels out (cross-session numbers never do).
# 3.1.62: a run WITHOUT -Ab now prints "ab=--" (there is only one arm, so there
# is no arm name to report).  Before 3.1.62 it printed ab=chain, which made a
# plain production run look like an A/B window.
$hit = Select-String -Path $log.FullName -Pattern 'ab=(chain|1seg|out|rb)'
if ($hit) { $hit | ForEach-Object { $_.Line } }
else { Write-Output "(NOT FOUND - needs BEAUTY_CHAIN_AB=1 and BEAUTY_PROFILE=1; a plain run prints ab=--)" }
Write-Output ""
Write-Output "---- all obs-beauty lines ----"
Select-String -Path $log.FullName -Pattern '\[obs-beauty\]' | ForEach-Object { $_.Line }
Write-Output ""
Write-Output "---- OBS-level warnings/errors ----"
Select-String -Path $log.FullName -Pattern '^\d\d:\d\d:\d\d\.\d+:\s+(warning|error):' |
    Where-Object { $_.Line -match 'beauty' } | ForEach-Object { $_.Line }
Write-Output ""
Write-Output "log path: $($log.FullName)"
