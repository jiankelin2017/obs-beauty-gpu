# =====================================================================
#  build_setup.ps1 - build the standalone one-click installer (Setup.exe)
#
#  Produces: .\Setup.exe  (next to this script)
#
#  WHAT IT PACKAGES (all embedded as RCDATA, extracted by setup.cpp):
#    obs-beauty.dll            the filter DLL (from the 02_* build folder)
#    onnxruntime.dll           inference runtime  (~11.5 MB, MIT)
#    yunet.onnx                face detection model (~232 KB, MIT)
#    THIRD-PARTY-NOTICES.md    license text for the two above
#    LICENSE                   this project's own license (GPL-2.0), verbatim
#                              FSF text -- byte-identical on purpose, see below
#    COPYRIGHT.md              copyright line + scope note; kept OUT of LICENSE
#                              because GitHub matches LICENSE against the
#                              official text and classifies anything else as
#                              "Other", losing the GPL-2.0 badge entirely
#    onnxruntime-ThirdPartyNotices.txt
#                              ORT's own notices (its internal deps)
#    shaders\*.hlsl            the 6 GPU shaders (from 01_*/shaders)
#    setup.manifest            UAC elevation manifest
#
#  WHY the runtime and the model are inside:
#    they used to be a manual post-install step. Without them the filter still
#    loads, so nothing errors out -- face detection just silently degrades to
#    full-frame smoothing. A package that "installs fine" but ships a crippled
#    engine is worse than one that fails loudly. Missing payload = no build.
#
#  VERSION:
#    read from 01_*/beauty_params.h -> BEAUTY_BUILD_STR, written to setup_ver.h,
#    force-included via /FI. Never hand-copied: the 3.0.x package kept showing
#    3.0.1 while the dll was already several releases ahead.
#
#  NOTE: this file is deliberately pure ASCII. PowerShell 5.1 decodes a
#  BOM-less .ps1 as ANSI, so a Chinese path literal would be mangled
#  (and a mangled comment can break the parse outright).
#  Every path is DISCOVERED (by wildcard) or DERIVED from $PSScriptRoot
#  instead of being written out.
#
#  NOTE: setup.rc refers to "obs-beauty.dll", "onnxruntime.dll", "yunet.onnx",
#  "THIRD-PARTY-NOTICES.md", "LICENSE", "COPYRIGHT.md",
#  "onnxruntime-ThirdPartyNotices.txt" and
#  "shaders\*.hlsl" with RELATIVE paths, so rc.exe
#  must run with the working directory set to this folder. The copies are
#  refreshed from their source folders on every run so the package can never
#  ship a stale artifact.
#
#  Usage:  powershell -ExecutionPolicy Bypass -File build_setup.ps1
# =====================================================================
$ErrorActionPreference = "Stop"

$pkgDir = $PSScriptRoot                              # the 07_* package folder
$root   = Split-Path -Parent $PSScriptRoot          # the project root

function Find-Dir([string]$parent, [string]$pattern) {
    $d = Get-ChildItem $parent -Directory -ErrorAction SilentlyContinue |
         Where-Object { $_.Name -like $pattern } | Select-Object -First 1
    if ($d) { return $d.FullName }
    return $null
}

function Need-File([string]$path, [string]$what) {
    if (-not (Test-Path -LiteralPath $path)) {
        throw ("missing payload ($what): " + $path)
    }
    return (Get-Item -LiteralPath $path)
}

# ---- locate toolchain ----------------------------------------------------
$msvcRoot = "C:\Program Files\Microsoft Visual Studio\18\Community\VC\Tools\MSVC\14.51.36231"
$kitRoot  = "C:\Program Files (x86)\Windows Kits\10"
$kitVer   = "10.0.26100.0"

$clExe = Join-Path $msvcRoot "bin\Hostx64\x64\cl.exe"
$rcExe = Join-Path $kitRoot "bin\$kitVer\x64\rc.exe"
if (-not (Test-Path $clExe)) { throw "cl.exe not found: $clExe" }
if (-not (Test-Path $rcExe)) { throw "rc.exe not found: $rcExe" }

$env:INCLUDE = "$msvcRoot\include;$kitRoot\Include\$kitVer\um;$kitRoot\Include\$kitVer\shared;$kitRoot\Include\$kitVer\ucrt"
$env:LIB     = "$msvcRoot\lib\x64;$kitRoot\Lib\$kitVer\um\x64;$kitRoot\Lib\$kitVer\ucrt\x64"

# ---- locate sources ------------------------------------------------------
$buildDir = Find-Dir $root '02_*'
$srcDir   = Find-Dir $root '01_*'
$offDir   = Find-Dir $root '06_*'
if (-not $buildDir) { throw "cannot locate build folder (02_*)" }
if (-not $srcDir)   { throw "cannot locate source folder (01_*)" }
if (-not $offDir)   { throw "cannot locate offline folder (06_*)" }

# ---- version: single source of truth -------------------------------------
$paramsH = Join-Path $srcDir "beauty_params.h"
Need-File $paramsH "beauty_params.h" | Out-Null
$m = Select-String -LiteralPath $paramsH -Pattern '#define\s+BEAUTY_BUILD_STR\s+"([0-9][0-9A-Za-z.\-]*)"' |
     Select-Object -First 1
if (-not $m) { throw "BEAUTY_BUILD_STR not found in $paramsH" }
$ver = $m.Matches[0].Groups[1].Value

$verHeader = Join-Path $pkgDir "setup_ver.h"
Set-Content -LiteralPath $verHeader -Encoding ascii -Value @(
    "// GENERATED by build_setup.ps1 from 01_*/beauty_params.h -- do not edit, do not commit.",
    "#define BEAUTY_SETUP_VER L`"$ver`""
)

# ---- refresh the payload from its sources --------------------------------
Copy-Item (Join-Path $buildDir "obs-beauty.dll") (Join-Path $pkgDir "obs-beauty.dll") -Force

# 3.2.4: the top-level "Beauty" menu panel (a SEPARATE obs module). Built by
# 02_*/build_ui.ps1. Shipping it is what makes the menu entry survive an
# install -- 3.2.3 purged it on install while carrying no copy of its own.
Copy-Item (Need-File (Join-Path $buildDir "obs-beauty-ui.dll") "obs-beauty-ui.dll").FullName `
          (Join-Path $pkgDir "obs-beauty-ui.dll") -Force

# Runtime + model: kept in the offline-verification folder because that is where
# the probe harness also needs them. Same file, two consumers.
Copy-Item (Need-File (Join-Path $offDir "onnxruntime.dll") "onnxruntime.dll").FullName `
          (Join-Path $pkgDir "onnxruntime.dll") -Force
Copy-Item (Need-File (Join-Path $offDir "models\yunet.onnx") "yunet.onnx").FullName `
          (Join-Path $pkgDir "yunet.onnx") -Force
Copy-Item (Need-File (Join-Path $root "THIRD-PARTY-NOTICES.md") "notices").FullName `
          (Join-Path $pkgDir "THIRD-PARTY-NOTICES.md") -Force
# This project's own license (GPL-2.0). GPL requires the license text to
# accompany distribution, so it ships with the installer.
# LICENSE is the unmodified FSF text -- do not prepend a copyright header here,
# or the file stops matching the official text and GitHub drops the badge.
Copy-Item (Need-File (Join-Path $root "LICENSE") "LICENSE").FullName `
          (Join-Path $pkgDir "LICENSE") -Force
# The copyright line and the scope note that used to sit at the top of LICENSE.
Copy-Item (Need-File (Join-Path $root "COPYRIGHT.md") "COPYRIGHT.md").FullName `
          (Join-Path $pkgDir "COPYRIGHT.md") -Force

# ONNX Runtime's own third-party notice (covers what ORT links internally:
# abseil, protobuf, ...). THIRD-PARTY-NOTICES.md only covers ORT itself.
# Taken VERBATIM from the upstream tag matching the dll we ship -- never
# hand-edited, the file is Microsoft's text.
Copy-Item (Need-File (Join-Path $root "third_party\onnxruntime-1.20.1-ThirdPartyNotices.txt") "ort notices").FullName `
          (Join-Path $pkgDir "onnxruntime-ThirdPartyNotices.txt") -Force

$pkgShaders = Join-Path $pkgDir "shaders"
if (-not (Test-Path $pkgShaders)) { New-Item -ItemType Directory -Force -Path $pkgShaders | Out-Null }
# P2-3: this folder is a BUILD ARTIFACT, never a source and never tracked by git.
# Wipe stale *.hlsl BEFORE copying so a shader that was renamed or deleted in
# 01_*/shaders cannot survive in the package as a ghost copy.
# Same PowerShell 5.1 trap as build_gpu.ps1: piping Get-ChildItem into
# Remove-Item throws InputObjectNotBound when objects arrive as PSObject.
# Use an explicit path wildcard instead.
Remove-Item (Join-Path $pkgShaders "*.hlsl") -Force -ErrorAction SilentlyContinue
$srcShaders = Join-Path $srcDir "shaders"
$hlsl = @(Get-ChildItem $srcShaders -Filter "*.hlsl")
if ($hlsl.Count -ne 6) { throw ("expected 6 shaders, found " + $hlsl.Count) }
$hlsl | ForEach-Object { Copy-Item $_.FullName (Join-Path $pkgShaders $_.Name) -Force }

# Sanity: the dll we just copied must be the version we are about to claim.
$dllBytes = [System.IO.File]::ReadAllBytes((Join-Path $pkgDir "obs-beauty.dll"))
$ascii = [System.Text.Encoding]::ASCII.GetString($dllBytes)
if (-not $ascii.Contains($ver)) {
    throw ("version mismatch: dll does not contain '" + $ver + "' -- rebuild 02_* first")
}

Write-Output ("version   : " + $ver)
Write-Output ("payload   : dll {0:N0} B, ort {1:N0} B, model {2:N0} B, {3} shaders" -f `
    (Get-Item (Join-Path $pkgDir "obs-beauty.dll")).Length, `
    (Get-Item (Join-Path $pkgDir "onnxruntime.dll")).Length, `
    (Get-Item (Join-Path $pkgDir "yunet.onnx")).Length, `
    $hlsl.Count)

# ---- compile -------------------------------------------------------------
Push-Location $pkgDir
& $rcExe /nologo /fo setup.res setup.rc
if ($LASTEXITCODE -ne 0) { Pop-Location; throw "rc.exe failed ($LASTEXITCODE)" }
& $clExe /nologo /O2 /EHsc /MT /utf-8 /FIsetup_ver.h setup.cpp setup.res /link /SUBSYSTEM:WINDOWS user32.lib advapi32.lib kernel32.lib shell32.lib /OUT:Setup.exe
$rc = $LASTEXITCODE
Pop-Location
if ($rc -ne 0) { throw "link failed ($rc)" }

$f = Get-Item (Join-Path $pkgDir "Setup.exe")
"BUILD OK: {0:N0} B  md5={1}" -f $f.Length, (Get-FileHash $f.FullName -Algorithm MD5).Hash
